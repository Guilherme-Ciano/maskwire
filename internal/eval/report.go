package eval

import (
	"fmt"
	"strings"
)

func pct(n, d int) string {
	if d == 0 {
		return "-"
	}
	return fmt.Sprintf("%.1f%%", 100*float64(n)/float64(d))
}

func (t TypeResult) total() Counts {
	var c Counts
	for _, p := range t.ByPres {
		c.Gold += p.Gold
		c.Hit += p.Hit
		c.Leak += p.Leak
	}
	return c
}

func Markdown(seed uint64, results []Result) string {
	var b strings.Builder
	fmt.Fprintf(&b, reportHeader, results[0].Docs, seed)
	for _, r := range results {
		fmt.Fprintf(&b, "\n## min_score %.1f\n\n", r.Threshold)
		b.WriteString("| Type | Precision | Recall labelled | Recall formatted | Recall bare | Leak rate |\n")
		b.WriteString("|---|---:|---:|---:|---:|---:|\n")
		for _, t := range r.Types {
			c := t.total()
			if c.Gold == 0 {
				continue
			}
			fmt.Fprintf(
				&b,
				"| `%s` | %s | %s | %s | %s | %s |\n",
				t.Type,
				pct(t.Pred-t.FP, t.Pred),
				pct(
					t.ByPres[Labelled].Hit,
					t.ByPres[Labelled].Gold,
				),
				pct(t.ByPres[Formatted].Hit, t.ByPres[Formatted].Gold),
				pct(t.ByPres[Bare].Hit, t.ByPres[Bare].Gold),
				pct(c.Leak, c.Gold),
			)
		}
		b.WriteString("\n| Hard negative | Flagged |\n|---|---:|\n")
		for _, n := range r.Negatives {
			fmt.Fprintf(&b, "| %s | %s (%d of %d) |\n", n.Kind, pct(n.Flagged, n.Seen), n.Flagged, n.Seen)
		}
	}
	return b.String()
}

const reportHeader = `# Detection evaluation

Generated by ` + "`go run ./internal/tools/evalreport`" + ` from %d synthetic documents (seed %d); the numbers are
reproducible and CI fails when this file is out of date.

Each document has one personal identifier and one or two hard negatives in short multilingual sentences. The
identifier is presented three ways: **labelled** (its keyword right before it, such as "CPF" or "IBAN"),
**formatted** (official grouping after a neutral word such as "ref") and **bare** (compact form after a neutral
word). Values are generated to pass their real checksums; hard negatives are near misses (one digit changed),
dates, prices, hashes, version strings and random numbers of ID length.

- **Precision**: detections of the type that match a planted value of that type.
- **Recall**: planted values detected with the right type.
- **Leak rate**: planted values not fully covered by any detection, which is what reaches the provider.
- **Flagged**: hard negatives that any detection overlapped.

Limits: the generator and the detector were written by the same author, so formats the generator does not produce
are not measured, and real text is messier. Some types are detected without a keyword only in their official
grouping (BSN, PESEL, SVNR, PIS and others, see the README), which is why their bare recall is low by design. Phone numbers
without ` + `, parentheses or a word such as "tel" are not detected on purpose, so bare phones leak. A
random 9-digit number passes the PT NIF checksum about 9%% of the time and an 11-digit one the CPF checksum about
1%%; those show up as flagged random numbers at ` + "`min_score 0`" + ` and disappear at 0.7, where bare
identifiers need a keyword or their official grouping.
`
