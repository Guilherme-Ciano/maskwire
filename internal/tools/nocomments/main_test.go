package main

import (
	"bytes"
	"go/token"
	"os"
	"path/filepath"
	"testing"
)

func TestCheck(t *testing.T) {
	t.Parallel()
	cases := []struct {
		name string
		src  string
		want int
	}{
		{"clean", "package x\n\nfunc f() {}\n", 0},
		{"line comment", "package x\n\n// f does things\nfunc f() {}\n", 1},
		{"block comment", "package x\n\n/* hi */\nfunc f() {}\n", 1},
		{"build directive", "//go:build linux\n\npackage x\n", 0},
		{"embed directive", "package x\n\nimport _ \"embed\"\n\n//go:embed a.txt\nvar s string\n", 0},
		{"generated header", "// Code generated by x. DO NOT EDIT.\n\npackage x\n", 0},
		{"nolint", "package x\n\nfunc f() {} //nolint:all\n", 1},
		{"trailing", "package x\n\nvar a = 1 // one\nvar b = 2 // two\n", 2},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			got, err := check(token.NewFileSet(), "x.go", tc.src)
			if err != nil {
				t.Fatal(err)
			}
			if len(got) != tc.want {
				t.Fatalf("got %d violations %v, want %d", len(got), got, tc.want)
			}
		})
	}
}

func TestRun(t *testing.T) {
	t.Parallel()
	dir := t.TempDir()
	write := func(rel, src string) {
		p := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(src), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("a.go", "package a\n")
	write("testdata/b.go", "package b\n\n// ignored\n")
	write(".hidden/c.go", "package c\n\n// ignored\n")
	var buf bytes.Buffer
	if code := run(dir, &buf); code != 0 {
		t.Fatalf("clean tree: code %d, out %q", code, buf.String())
	}
	write("sub/d.go", "package d\n\n// bad\n")
	buf.Reset()
	if code := run(dir, &buf); code != 1 {
		t.Fatalf("dirty tree: code %d", code)
	}
	write("sub/e.go", "package e\n\nfunc {")
	buf.Reset()
	if code := run(dir, &buf); code != 2 {
		t.Fatalf("broken tree: code %d", code)
	}
}
